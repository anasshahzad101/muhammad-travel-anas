function mulberry(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const q = (n: number) => Math.round(n * 10) / 10;

/**
 * Dots for the night lights: `core` for the bright points, `field` for the
 * dimmer spread around them, and `blooms`, the soft glow over the big cities.
 */
export function nightLights(): { core: string; field: string; blooms: { x: number; y: number; r: number }[] } {
  const r = mulberry(1447);
  const core: string[] = [];
  const field: string[] = [];
  const blooms: { x: number; y: number; r: number }[] = [];
  const dot = (list: string[], x: number, y: number) => {
    if (x < -4 || x > 1004 || y < -4 || y > 564) return;
    list.push(`M${q(x)} ${q(y)}h.1`);
  };
  for (const [lat, lon, w] of PLACES) {
    const [cx, cy] = projectLonLat(lon, lat);
    if (w >= 5) blooms.push({ x: q(cx), y: q(cy), r: q(3 + w * 1.5) });
    const n = Math.round(6 + Math.pow(w, 1.75) * 4.4);
    const spread = 1.1 + w * 0.5;
    for (let i = 0; i < n; i++) {
      // Dense in the middle, thinning outwards
      const a = r() * Math.PI * 2;
      const d = (r() + r()) * 0.5 * spread * (r() < 0.2 ? 1.8 : 1);
      dot(d < spread * 0.45 ? core : field, cx + Math.cos(a) * d, cy + Math.sin(a) * d * 0.85);
    }
  }
  for (const line of CORRIDORS) {
    const pts = line.map(([lat, lon]) => projectLonLat(lon, lat));
    for (let i = 0; i < pts.length - 1; i++) {
      const [x0, y0] = pts[i];
      const [x1, y1] = pts[i + 1];
      const steps = Math.max(2, Math.round(Math.hypot(x1 - x0, y1 - y0) / 1.6));
      for (let s = 0; s < steps; s++) {
        if (r() < 0.3) continue;
        const t = s / steps;
        dot(field, x0 + (x1 - x0) * t + (r() - 0.5) * 1.6, y0 + (y1 - y0) * t + (r() - 0.5) * 1.6);
      }
    }
  }
  return { core: core.join(""), field: field.join(""), blooms };
}

/** Faint lines of latitude and longitude every 5 degrees, curved as the projection curves them. */
export function graticule(): string {
  const parts: string[] = [];
  const line = (pts: [number, number][]) => parts.push(pts.map(([x, y], i) => `${i ? "L" : "M"}${q(x)} ${q(y)}`).join(""));
  for (let lon = 25; lon <= 85; lon += 5) {
    const pts: [number, number][] = [];
    for (let lat = 8; lat <= 42; lat += 2) pts.push(projectLonLat(lon, lat));
    line(pts);
  }
  for (let lat = 10; lat <= 40; lat += 5) {
    const pts: [number, number][] = [];
    for (let lon = 20; lon <= 90; lon += 2) pts.push(projectLonLat(lon, lat));
    line(pts);
  }
  return parts.join("");
}
